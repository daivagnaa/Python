#Arithmetic
a = 2
b = 4
print(a+b , b-a , b*a , b/a , b**a , b//a , end="\n")

#Comparision 
print(a==b , a!=b , a>b , a<b, end="\n")

#Logical
print(True and False)
print(True or False)

#Assignment
a=b
print(a,b)
a += 10
print(a)
b -= 2
print(b, end="\n")

#Membership
String = ("Hello","Hi","Yeah")
